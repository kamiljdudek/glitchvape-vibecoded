=head1 NAME

GlitchVape::Effect::Overlay - text, camcorder furniture and drawn graphics

=head1 DESCRIPTION

Everything drawn on top of the picture rather than done to it. These run last,
because on-screen display is generated by the camera or the player and is not
subject to the tape damage the picture went through -- which is exactly why
crisp white C<REC> text over a degraded image reads as authentic.

