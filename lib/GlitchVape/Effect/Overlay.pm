sub _text
{
    my ( $ctx, $p ) = @_;
    return if $p->{ opacity } <= 0;

    my $rng = $ctx->rng_for( 'text' );

    # An empty string means "surprise me", which is how the presets get
    # varied Japanese text without naming a phrase in every one.
    my $str = $p->{ string };
    if ( !length $str )
    {
        $str = $rng->pick( @PHRASES );
    }

    # Wide tracking is done by hand because ImageMagick has no letter-spacing
    # control; inserting thin spaces is the usual workaround.
    if ( $p->{ spacing } > 0 )
    {
        my $gap = ' ' x ( int( $p->{ spacing } / 8 ) || 1 );
        $str = join $gap, split //, $str;
    }

    my ( $w, $h ) = $ctx->dims;
    my $font =
        GlitchVape::Fonts::resolve_or_die( $p->{ font }, "effect 'text'" );
    my $size = int( $h * $p->{ size } / 100 ) || 8;

    my $dx = int( $w * $p->{ x } );
    my $dy = int( $h * $p->{ y } );

    my %common = (
        string  => $str,
        font    => $font,
        size    => $size,
        gravity => $p->{ gravity },
        opacity => $p->{ opacity },
        rotate  => $p->{ rotate },
    );

    if ( length $p->{ shadow } && $p->{ shadow_offset } )
    {
        _annotate(
            $ctx, %common,
            color => $p->{ shadow },
            x     => $dx + $p->{ shadow_offset },
            y     => $dy + $p->{ shadow_offset },
        );
    }

    _annotate( $ctx, %common, color => $p->{ color }, x => $dx, y => $dy );
    return;
}

