sub _chicago
{
    my ( $ctx, $p ) = @_;

    my ( $iw, $ih ) = $ctx->dims;
    return unless $iw && $ih;

    my $zoom = int( $p->{ zoom } || 0 ) || _chicago_zoom( $ih );

    # The window is asked for in the picture's pixels and built in its own, so
    # the division happens here and the module never hears about zoom.
    my $want_w = _round( $iw * $p->{ width } );
    my $want_h = _round( $ih * $p->{ height } );

    my $win = GlitchVape::Chicago::render(
        width      => int( $want_w / $zoom ),
        height     => int( $want_h / $zoom ),
        theme      => $p->{ theme },
        icon       => $p->{ icon },
        caption    => $p->{ title },
        menu       => $p->{ menu },
        font       => GlitchVape::Fonts::resolve( $p->{ font } ),
        type_size  => $p->{ type_size },
        scrollbars => $p->{ scrollbars },
        grip       => $p->{ grip },
        thumb      => $p->{ thumb },
        scroll     => $p->{ scroll },
    );

    # What it gave back rather than what was asked for: render() clamps up to
    # the smallest window its parts fit in, so a window asked to be narrower
    # than its own caption buttons comes back wider.
    my ( $cw, $ch ) = ( $win->Get( 'width' ), $win->Get( 'height' ) );

    if ( $zoom > 1 )
    {
        # Sample, not Resize. Sample replicates pixels; Resize interpolates,
        # and an interpolated one-pixel highlight is a grey smear that stops
        # the bevel reading as raised at all.
        GlitchVape::Magick::check(
            $win->Sample(
                geometry => sprintf '%dx%d!',
                $cw * $zoom, $ch * $zoom
            ),
            'chicago: could not enlarge the window'
        );
    }

    if ( $p->{ opacity } < 1 )
    {
        $win->Evaluate(
            operator => 'Multiply',
            value    => $p->{ opacity },
            channel  => 'Alpha',
        );
    }

    my ( $x, $y ) = _chicago_place( $p, $iw, $ih, $cw * $zoom, $ch * $zoom );
    ( $x, $y ) = _chicago_dance( $ctx, $p, $zoom, $x, $y );

    GlitchVape::Magick::check(
        $ctx->image->Composite(
            image   => $win->[ 0 ],
            compose => 'Over',
            x       => $x,
            y       => $y,
        ),
        'chicago: could not place the window'
    );

    return;
}

# A new place every frame, near the one it was put in. Not a drift: everywhere
# else here that word is a journey, a pattern travelling in a direction and
# snapped to whole repeats so that it arrives back where it set out. This is a
# window that will not sit still, which is a different thing and gets a
# different word.
#
# It closes its loop all the same, and by an easier route. Context::rng_phase
# keys the roll on where the frame sits around the loop rather than on which
# frame it is, so the frame after the last one is the first one again; and the
# seam is invisible regardless, because every frame is already somewhere else
# and one more jump among them reads as one more jump.
#
# Measured in the window's own pixels and multiplied up by the zoom, so the
# dance is the same size on the screen whatever the picture's resolution --
# and so the window stays on the grid it was drawn on, which a jump of some
# other number of image pixels would not disturb but would look arbitrary
# beside everything else here.
sub _chicago_dance
{
    my ( $ctx, $p, $zoom, $x, $y ) = @_;

    my $most = $p->{ jitter } || 0;

    return ( $x, $y ) if $most <= 0 || $ctx->frames <= 1;

    my $rng = $ctx->rng_phase( 'chicago' );

    return (
        $x + $zoom * _round( $rng->between( -$most, $most ) ),
        $y + $zoom * _round( $rng->between( -$most, $most ) ),
    );
}

# One window pixel per image pixel would leave a four-pixel border on a
# twelve-megapixel photograph, which is a hairline nobody would read as a
# window. The picture is treated as a screen 480 pixels tall -- the height of
# the screenshot every measurement in GlitchVape::Chicago came off -- and the
# zoom is however many times bigger than that it is.
sub _chicago_zoom
{
    my ( $height ) = @_;

    my $zoom = _round( $height / 480 );

    return $zoom < 1 ? 1 : $zoom;
}

# Insets from the anchor rather than plain offsets, which is what the rest of
# the overlay effects mean by x and y: at NorthEast a positive x moves the
# window left, because it is moving away from the edge it is against.
sub _chicago_place
{
    my ( $p, $iw, $ih, $ww, $wh ) = @_;

    my $dx = _round( $iw * $p->{ x } );
    my $dy = _round( $ih * $p->{ y } );

    my $gravity = $p->{ gravity } // 'Center';

    my $x =
          $gravity =~ /West/ ? $dx
        : $gravity =~ /East/ ? $iw - $ww - $dx
        :                      int( ( $iw - $ww ) / 2 ) + $dx;

    my $y =
          $gravity =~ /North/ ? $dy
        : $gravity =~ /South/ ? $ih - $wh - $dy
        :                       int( ( $ih - $wh ) / 2 ) + $dy;

    return ( $x, $y );
}

