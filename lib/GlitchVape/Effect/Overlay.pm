sub _grid
{
    my ( $ctx, $p ) = @_;
    return if $p->{ opacity } <= 0;
    require Image::Magick;

    my ( $w, $h ) = $ctx->dims;
    my $hy = int( $h * $p->{ horizon } );
    my $cx = int( $w / 2 );

    my $layer = Image::Magick->new( size => "${w}x${h}" );
    GlitchVape::Magick::check( $layer->Read( 'xc:transparent' ),
        "grid: could not create layer" );

    _draw_sun( $layer, $p, $w, $h ) if $p->{ sun };

    my @draw;

    # Horizontal lines: t^perspective spaces them tightly at the horizon and
    # widely at the bottom of the frame.
    #
    # Drift moves them along that curve rather than down the screen, which is
    # the whole trick: a line travelling at constant speed in t accelerates
    # towards the viewer exactly as the spacing widens, so the plane reads as
    # ground going past instead of as stripes sliding. One line spacing is the
    # repeat, so travel() snaps to whole lines and the loop closes with a line
    # sitting where its neighbour started.
    #
    # Only these move. The vertical lines converge on the vanishing point and
    # are the same set of rays whatever the ground is doing; scrolling them
    # would swing the whole plane sideways.
    my $shift = $ctx->travel( $p->{ drift }, 1 );
    my $extra = int( abs $p->{ drift } ) + 1;

    for my $i ( 1 - $extra .. $p->{ lines_h } + $extra )
    {
        my $t = ( $i + $shift ) / $p->{ lines_h };

        # Off the top past the horizon, or off the bottom of the frame.
        next if $t <= 0 || $t > 1;

        my $y = $hy + ( $h - $hy ) * ( $t**$p->{ perspective } );
        push @draw, sprintf( 'line 0,%.1f %d,%.1f', $y, $w, $y );
    }

    # Vertical lines all converge on the vanishing point. Spreading their
    # bottom ends well past the frame edges keeps the outermost ones steep
    # enough to look like part of the same plane.
    if ( $p->{ lines_v } )
    {
        my $spread = $w * 2.5;
        for my $i ( 0 .. $p->{ lines_v } )
        {
            my $t = $i / $p->{ lines_v };
            my $x = $cx - $spread / 2 + $spread * $t;
            push @draw, sprintf( 'line %d,%d %.1f,%d', $cx, $hy, $x, $h );
        }
    }

    if ( @draw )
    {
        for my $d ( @draw )
        {
            my ( $prim, @pts ) = split ' ', $d;
            $layer->Draw(
                primitive   => $prim,
                points      => join( ' ', @pts ),
                stroke      => $p->{ color },
                strokewidth => $p->{ width },
                fill        => 'none',
                antialias   => 'true',
            );
        }
    }

    if ( $p->{ opacity } < 1 )
    {
        $layer->Evaluate(
            operator => 'Multiply',
            value    => $p->{ opacity },
            channel  => 'Alpha',
        );
    }

    $ctx->image->Composite( image => $layer->[ 0 ], compose => 'Over' );
    return;
}

sub _draw_sun
{
    my ( $layer, $p, $w, $h ) = @_;
    require Image::Magick;

    # Horizon and centre are derived rather than passed in: they are a
    # function of the geometry the caller already hands over.
    my $hy = int( $h * $p->{ horizon } );
    my $cx = int( $w / 2 );

    my $d = int( $w * $p->{ sun_size } );
    return if $d < 4;
    my $r = int( $d / 2 );

    my @cols = split /\s*,\s*/, $p->{ sun_colors };
    push @cols, $cols[ 0 ] if @cols < 2;

    # Build the sun as its own square image: a vertical gradient masked by a
    # circle. Drawing a gradient-filled circle directly is not something
    # ImageMagick's draw primitives can do.
    my $disc = Image::Magick->new( size => "${d}x${d}" );
    $disc->Read( "gradient:$cols[0]-$cols[1]" );

    my $mask = Image::Magick->new( size => "${d}x${d}" );
    $mask->Read( 'xc:black' );
    $mask->Draw(
        primitive => 'circle',
        points    => sprintf( '%d,%d %d,%d', $r, $r, $r, 0 ),
        fill      => 'white',
        stroke    => 'none',
    );

    # Slots across the lower half, widening towards the bottom.
    if ( $p->{ sun_bands } )
    {
        for my $i ( 1 .. $p->{ sun_bands } )
        {
            my $t  = $i / ( $p->{ sun_bands } + 1 );
            my $y  = $r + ( $d - $r ) * ( $t**1.4 );
            my $th = 1 + $t * $r * 0.16;
            $mask->Draw(
                primitive   => 'line',
                points      => sprintf( '0,%.1f %d,%.1f', $y, $d, $y ),
                stroke      => 'black',
                strokewidth => $th,
                fill        => 'none',
            );
        }
    }

    # The mask carries the shape as black and white pixels, so its intensity
    # has to be moved into its alpha channel before the composite. IM6's
    # CopyOpacity fell back to intensity when the source had no alpha; IM7
    # aliases CopyOpacity to CopyAlpha, which copies the alpha channel and
    # nothing else -- and `xc:black` arrives with a fully opaque one. Without
    # the copy the sun composites as an opaque square with no slots in it.
    $mask->Set( alpha => 'copy' );

    $disc->Set( alpha => 'on' );
    $disc->Composite( image => $mask->[ 0 ], compose => 'CopyAlpha' );

    my $x = $cx - $r;
    my $y = $hy - int( $r * 1.15 );

    $layer->Composite(
        image   => $disc->[ 0 ],
        compose => 'Over',
        x       => $x,
        y       => $y
    );
    return;
}

