sub _letterbox
{
    my ( $ctx, $p ) = @_;

    if ( length $p->{ ratio } )
    {
        my ( $rw, $rh ) =
            $p->{ ratio } =~
            m{^\s*(\d+(?:\.\d+)?)\s*[:x/]\s*(\d+(?:\.\d+)?)\s*$}
            or die
            "letterbox: ratio must look like '16:9', got '$p->{ratio}'\n";

        my ( $w, $h ) = $ctx->dims;
        my $target = $rw / $rh;
        my $cur    = $w / $h;

        my ( $nw, $nh ) =
            $cur > $target
            ? ( $w, int( $w / $target ) )
            : ( int( $h * $target ), $h );

        $ctx->magick(
            '-background', $p->{ color }, '-gravity', 'Center',
            '-extent',     "${nw}x${nh}",
        );
    }

    if ( $p->{ border } > 0 )
    {
        my ( $w, $h ) = $ctx->dims;

        # Border width is a fraction of the shorter side, so a panorama does
        # not get an absurdly thick frame on its short edge.
        my $shorter = $h;
        if ( $w < $h )
        {
            $shorter = $w;
        }

        my $b = int( $shorter * $p->{ border } );
        $ctx->magick( '-bordercolor', $p->{ color }, '-border', $b ) if $b > 0;
    }
    return;
}

