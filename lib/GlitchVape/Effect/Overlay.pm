sub _osd
{
    my ( $ctx, $p ) = @_;

    my ( $w, $h ) = $ctx->dims;
    my $rng = $ctx->rng_for( 'osd' );
    my $font =
        GlitchVape::Fonts::resolve_or_die( $p->{ font }, "effect 'osd'" );
    my $size = int( $h * $p->{ size } / 100 ) || 10;

    my $mx = int( $w * $p->{ margin } );
    my $my = int( $h * $p->{ margin } );

    # Every piece of on-screen display shares its face, size and colour; only
    # the string and corner change.
    my %osd = ( font => $font, size => $size, color => $p->{ color } );

    if ( $p->{ rec } )
    {
        # The dot blinks across an animation, as the real indicator does.
        # The record dot blinks across an animation, as the real indicator
        # does, and is simply always lit on a still.
        my $on = 1;
        if ( $ctx->frames > 1 )
        {
            $on = 0;
            if ( $ctx->phase < 0.6 )
            {
                $on = 1;
            }
        }

        if ( $on )
        {
            my $r  = int( $size * 0.32 );
            my $cx = $mx + $r;
            my $cy = $my + int( $size * 0.42 );
            $ctx->magick( '-fill', '#FF2020', '-stroke', 'none', '-draw',
                sprintf( 'circle %d,%d %d,%d', $cx, $cy, $cx + $r, $cy ),
            );
        }

        _annotate(
            $ctx, %osd,
            string  => $p->{ rec_text },
            gravity => 'NorthWest',
            x       => $mx + int( $size * 0.95 ),
            y       => $my,
        );
    }

    if ( $p->{ play } )
    {
        my $y   = $my + int( $size * 1.6 );
        my $tri = int( $size * 0.45 );
        my $x0  = $mx;
        $ctx->magick(
            '-fill',
            $p->{ color },
            '-stroke',
            'none', '-draw',
            sprintf(
                'polygon %d,%d %d,%d %d,%d',
                $x0, $y, $x0,
                $y + $tri * 2,
                $x0 + $tri * 1.7,
                $y + $tri
            ),
        );
        _annotate(
            $ctx, %osd,
            string  => 'PLAY',
            gravity => 'NorthWest',
            x       => $mx + int( $size * 0.95 ),
            y       => $y - int( $size * 0.15 ),
        );
    }

    if ( $p->{ timestamp } )
    {
        # A literal date wins; otherwise invent a plausible 1990s one, since
        # a real present-day timestamp undercuts the whole conceit.
        my $date = $p->{ date };
        if ( !length $date )
        {
            $date = _fake_date( $rng );
        }

        my $time = $p->{ time };
        if ( !length $time )
        {
            $time = _fake_time( $rng );
        }

        _annotate(
            $ctx, %osd,
            string  => $time,
            gravity => 'SouthEast',
            x       => $mx,
            y       => $my,
        );
        _annotate(
            $ctx, %osd,
            string  => $date,
            gravity => 'SouthEast',
            x       => $mx,
            y       => $my + int( $size * 1.25 ),
        );
    }

    if ( length $p->{ mode } )
    {
        _annotate(
            $ctx, %osd,
            string  => $p->{ mode },
            gravity => 'NorthEast',
            x       => $mx,
            y       => $my,
        );
    }
    return;
}

my @MONTH = qw(JAN FEB MAR APR MAY JUN JUL AUG SEP OCT NOV DEC);

sub _fake_date
{
    my ( $rng ) = @_;
    return sprintf '%s %02d %d',
        $rng->pick( @MONTH ),
        $rng->int_between( 1,    28 ),
        $rng->int_between( 1990, 1999 );
}

sub _fake_time
{
    my ( $rng ) = @_;

    # 12-hour with a leading space, the way the cheap OSD chips rendered it.
    my $meridiem = 'PM';
    if ( $rng->chance( 0.5 ) )
    {
        $meridiem = 'AM';
    }

    return sprintf '%s %2d:%02d',
        $meridiem,
        $rng->int_between( 1, 12 ),
        $rng->int_between( 0, 59 );
}

